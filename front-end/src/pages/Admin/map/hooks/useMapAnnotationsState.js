import { useState, useEffect, useMemo, useCallback } from "react";
import axios from "axios";
import L from "leaflet";
import { API_BASE_URL } from "../../../../config/api";
import { showToast } from "../../../../components/GlobalToast";
import { getPropertyFallbackCoordinates } from "../../../../utils/geocoding";
import { mergeGeneratedRoadAnnotations } from "../../../../utils/pdfLotImport/roadLabels";
import { getAuthConfig } from "../utils/mapConstants";

export function useMapAnnotationsState({
  map,
  selectedProperty,
  mapData,
  isEditingOverlay,
  setIsEditingOverlay,
  handleLotUpdated,
  automaticRoadAnnotations = [],
}) {
  const [showAnnotationPanel, setShowAnnotationPanel] = useState(false);
  const [isEditingAnnotations, setIsEditingAnnotations] = useState(true);
  const [activeAnnotationId, setActiveAnnotationId] = useState(null);
  const [selectedAnnotationIds, setSelectedAnnotationIds] = useState([]);
  const [annotations, setAnnotations] = useState([]);
  const [isSavingAnnotations, setIsSavingAnnotations] = useState(false);

  // Auto-clean selected IDs when annotations change
  useEffect(() => {
    setSelectedAnnotationIds((prev) =>
      prev.filter((id) => annotations.some((a) => a.id === id && !a.deleted))
    );
  }, [annotations]);

  // Sync annotations when selectedProperty or mapData changes
  useEffect(() => {
    if (selectedProperty && mapData?.properties) {
      const prop = mapData.properties.find(
        (p) => Number(p.property_id) === Number(selectedProperty)
      );
      if (prop && prop.annotations) {
        try {
          const parsed =
            typeof prop.annotations === "string"
              ? JSON.parse(prop.annotations)
              : prop.annotations;
          if (Array.isArray(parsed)) {
            setAnnotations(parsed);
            if (parsed.length > 0) setActiveAnnotationId(parsed[0].id);
          } else {
            setAnnotations([]);
          }
        } catch (e) {
          setAnnotations([]);
        }
      } else {
        setAnnotations([]);
      }
    }
  }, [selectedProperty, mapData]);

  // All annotations across all active properties so labels appear without clicking dropdown
  const allPropertiesAnnotations = useMemo(() => {
    if (!mapData?.properties) return [];
    const result = [];
    mapData.properties.forEach((p) => {
      const isSelected = Number(p.property_id) === Number(selectedProperty);
      if (isSelected) {
        const visibleAnnotations = isEditingOverlay
          ? annotations.filter((a) => a.autoGenerated !== "pdf-road")
          : annotations;
        result.push(...visibleAnnotations.map((a) => ({ ...a, property_id: p.property_id })));
        return;
      }
      if (!p.annotations) return;
      try {
        const parsed =
          typeof p.annotations === "string" ? JSON.parse(p.annotations) : p.annotations;
        if (Array.isArray(parsed)) {
          result.push(
            ...parsed.map((a) => ({ ...a, property_id: p.property_id }))
          );
        }
      } catch (e) {}
    });
    return result.filter((item) => !item.deleted);
  }, [mapData, selectedProperty, annotations, isEditingOverlay]);

  // Listen for openAnnotationPanel event from AdminHeader
  useEffect(() => {
    const handleOpenAnnotationEvent = () => {
      setShowAnnotationPanel((prev) => !prev);
      setIsEditingAnnotations(true);
    };
    window.addEventListener("openAnnotationPanel", handleOpenAnnotationEvent);
    return () =>
      window.removeEventListener("openAnnotationPanel", handleOpenAnnotationEvent);
  }, []);

  const handleAddAnnotation = useCallback(() => {
    const property = mapData?.properties?.find(
      (item) => Number(item.property_id) === Number(selectedProperty)
    );
    const fallback = getPropertyFallbackCoordinates(
      selectedProperty, property?.location, property?.property_name
    );
    const center = map
      ? map.getCenter()
      : {
          lat: fallback[0],
          lng: fallback[1],
        };
    const newId = "label_" + Date.now();
    const newLabel = {
      id: newId,
      property_id: Number(selectedProperty),
      text: `ROAD LOT ${annotations.length + 1} (6.50 M. WIDE)`,
      lat: center.lat,
      lng: center.lng,
      rotation: 0,
      fontSize: 12,
      color: "#e2e8f0",
      scaleWithMap: true,
    };
    setAnnotations((prev) => [...prev, newLabel]);
    setActiveAnnotationId(newId);
    setIsEditingAnnotations(true);
    setShowAnnotationPanel(true);
  }, [map, annotations.length, selectedProperty, mapData]);

  const handleGenerateBlockLabels = useCallback(() => {
    if (!selectedProperty || !mapData?.lots) {
      showToast("Please select a property first.", "info");
      return;
    }
    const propLots = mapData.lots.filter(
      (l) => Number(l.property_id) === Number(selectedProperty)
    );
    if (!propLots.length) {
      showToast("No mapped lots found for this property.", "info");
      return;
    }

    const blockGroups = new Map();
    propLots.forEach((lot) => {
      const match = String(lot.lot_number || "").match(/^(Block\s+[0-9A-Za-z-]+)/i);
      if (!match) return;
      const bName = match[1].trim();
      if (!blockGroups.has(bName)) {
        blockGroups.set(bName, { lats: [], lngs: [] });
      }

      if (lot._centerLat != null && lot._centerLng != null) {
        blockGroups.get(bName).lats.push(lot._centerLat);
        blockGroups.get(bName).lngs.push(lot._centerLng);
      } else if (lot.coordinates) {
        try {
          const coords = typeof lot.coordinates === "string" ? JSON.parse(lot.coordinates) : lot.coordinates;
          if (Array.isArray(coords) && coords.length > 0) {
            let latSum = 0, lngSum = 0, ptCount = 0;
            coords.forEach((pt) => {
              if (Array.isArray(pt) && pt.length >= 2) {
                latSum += Number(pt[0]);
                lngSum += Number(pt[1]);
                ptCount++;
              }
            });
            if (ptCount > 0) {
              blockGroups.get(bName).lats.push(latSum / ptCount);
              blockGroups.get(bName).lngs.push(lngSum / ptCount);
            }
          }
        } catch (e) {}
      }
    });

    const newBlockLabels = [];
    blockGroups.forEach((coords, bName) => {
      if (!coords.lats.length) return;
      const alreadyExists = annotations.some(
        (a) => !a.deleted && String(a.text || "").toLowerCase().trim() === bName.toLowerCase().trim()
      );
      if (alreadyExists) return;

      const avgLat = coords.lats.reduce((a, b) => a + b, 0) / coords.lats.length;
      const avgLng = coords.lngs.reduce((a, b) => a + b, 0) / coords.lngs.length;

      newBlockLabels.push({
        id: "label_block_" + Date.now() + "_" + Math.random().toString(36).substr(2, 6),
        property_id: Number(selectedProperty),
        text: bName.toUpperCase(),
        lat: avgLat,
        lng: avgLng,
        rotation: 0,
        fontSize: 16,
        color: "#ffffff",
        scaleWithMap: true,
      });
    });

    if (newBlockLabels.length > 0) {
      setAnnotations((prev) => [...prev, ...newBlockLabels]);
      setActiveAnnotationId(newBlockLabels[0].id);
      setIsEditingAnnotations(true);
      setShowAnnotationPanel(true);
      showToast(`Added ${newBlockLabels.length} block labels! You can now drag them anywhere, adjust font size, and click Save.`, "success");
    } else {
      showToast("All block labels are already in your list.", "info");
      setShowAnnotationPanel(true);
    }
  }, [selectedProperty, mapData, annotations]);

  const handleToggleSelectAnnotation = useCallback((id) => {
    setSelectedAnnotationIds((prev) => {
      const next = prev.includes(id)
        ? prev.filter((item) => item !== id)
        : [...prev, id];
      if (next.length === 1) {
        setActiveAnnotationId(next[0]);
      } else if (!next.includes(activeAnnotationId) && next.length > 0) {
        setActiveAnnotationId(next[next.length - 1]);
      }
      return next;
    });
  }, [activeAnnotationId]);

  const handleSelectAllAnnotations = useCallback(() => {
    const allIds = annotations.filter((a) => !a.deleted).map((a) => a.id);
    setSelectedAnnotationIds(allIds);
    if (allIds.length > 0 && !allIds.includes(activeAnnotationId)) {
      setActiveAnnotationId(allIds[0]);
    }
  }, [annotations, activeAnnotationId]);

  const handleDeselectAllAnnotations = useCallback(() => {
    setSelectedAnnotationIds([]);
  }, []);

  const handleUpdateSelectedAnnotations = useCallback((updates) => {
    const targetIds = selectedAnnotationIds.length > 0
      ? selectedAnnotationIds
      : (activeAnnotationId ? [activeAnnotationId] : []);
    if (targetIds.length === 0) return;

    setAnnotations((prev) =>
      prev.map((a) => {
        if (!targetIds.includes(a.id) || a.deleted) return a;
        const computed = typeof updates === "function" ? updates(a) : updates;
        return {
          ...a,
          ...computed,
          ...(a.autoGenerated === "pdf-road" ? { pdfOverrides: { ...a.pdfOverrides, ...computed } } : {})
        };
      })
    );
  }, [selectedAnnotationIds, activeAnnotationId]);

  const handleDeleteSelectedAnnotations = useCallback(() => {
    const targetIds = selectedAnnotationIds.length > 0
      ? selectedAnnotationIds
      : (activeAnnotationId ? [activeAnnotationId] : []);
    if (targetIds.length === 0) return;

    setAnnotations((prev) =>
      prev.flatMap((a) => {
        if (!targetIds.includes(a.id)) return [a];
        return a.autoGenerated === "pdf-road" ? [{ ...a, deleted: true }] : [];
      })
    );
    setSelectedAnnotationIds([]);
    setActiveAnnotationId(null);
  }, [selectedAnnotationIds, activeAnnotationId]);

  const handleUpdateAnnotation = useCallback((id, updates) => {
    setAnnotations((prev) =>
      prev.map((a) => (a.id === id ? { ...a, ...updates,
        ...(a.autoGenerated === "pdf-road" ? { pdfOverrides: { ...a.pdfOverrides, ...updates } } : {}) } : a))
    );
  }, []);

  const handleUpdateAllAnnotations = useCallback((updates) => {
    setAnnotations((prev) =>
      prev.map((a) => (!a.deleted ? {
        ...a,
        ...updates,
        ...(a.autoGenerated === "pdf-road" ? { pdfOverrides: { ...a.pdfOverrides, ...updates } } : {})
      } : a))
    );
  }, []);

  const handleDeleteAnnotation = useCallback(
    (id) => {
      setAnnotations((prev) => prev.flatMap((a) => a.id !== id ? [a] : a.autoGenerated === "pdf-road" ? [{ ...a, deleted: true }] : []));
      if (activeAnnotationId === id) {
        setActiveAnnotationId(null);
      }
    },
    [activeAnnotationId]
  );

  const handleDeleteAllAnnotations = useCallback(() => {
    setAnnotations((prev) =>
      prev.flatMap((a) => (a.autoGenerated === "pdf-road" ? [{ ...a, deleted: true }] : []))
    );
    setActiveAnnotationId(null);
  }, []);

  const createRoadLabelIcon = useCallback((item, isEditing, isSelected) => {
    // Scaling is handled by CSS variable --road-label-scale (set on map container)
    return L.divIcon({
      className: "map-road-label-icon",
      html: `
        <div class="map-road-label-inner" style="
          position: absolute;
          left: 0;
          top: 0;
          transform: translate(-50%, -50%) rotate(${item.rotation || 0}deg) scale(var(--pdf-road-label-scale, 1));
          transform-origin: center center;
          color: ${item.color || '#e2e8f0'};
          font-size: ${item.fontSize || 13}px;
          font-weight: 800;
          font-family: system-ui, -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;
          letter-spacing: 0;
          text-shadow: 0 1px 3px rgba(0,0,0,0.95), 0 0 6px rgba(0,0,0,0.9);
          white-space: nowrap;
          user-select: none;
          pointer-events: ${isEditing ? 'auto' : 'none'};
          cursor: ${isEditing ? 'grab' : 'default'};
          padding: ${isEditing ? '5px 12px' : '2px 4px'};
          border: ${isEditing ? (isSelected ? '2px solid #38bdf8' : '1.5px dashed rgba(255,255,255,0.7)') : 'none'};
          border-radius: 6px;
          background: ${isEditing ? (isSelected ? 'rgba(14, 165, 233, 0.45)' : 'rgba(15, 23, 42, 0.75)') : 'transparent'};
          box-shadow: ${isEditing ? (isSelected ? '0 0 14px rgba(56, 189, 248, 0.8), 0 2px 8px rgba(0,0,0,0.8)' : '0 2px 8px rgba(0,0,0,0.6)') : 'none'};
          transition: border-color 0.15s ease, background-color 0.15s ease;
        ">
          <span>${String(item.text || '').replace(/[&<>"']/g, (char) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[char]))}</span>
        </div>
      `,
      iconSize: [0, 0],
      iconAnchor: [0, 0],
    });
  }, []);

  const persistAnnotations = useCallback(async (nextAnnotations, notify = false) => {
    if (!selectedProperty) return;
    setIsSavingAnnotations(true);
    try {
      await axios.put(
        `${API_BASE_URL}/api/properties/${selectedProperty}/annotations`,
        { annotations: nextAnnotations },
        getAuthConfig()
      );
      if (notify) showToast("Road & map labels saved successfully to database!", "success");
      if (handleLotUpdated) await handleLotUpdated();
      return true;
    } catch (err) {
      console.error("Error saving map annotations:", err);
      showToast(err.response?.data?.error || "Blueprint aligned, but the road labels could not be saved. Open Road Labels and try Save again.", "error");
      return false;
    } finally {
      setIsSavingAnnotations(false);
    }
  }, [selectedProperty, handleLotUpdated]);

  const handleSaveAnnotations = useCallback(async () => {
    await persistAnnotations(annotations, true);
  }, [annotations, persistAnnotations]);

  const handleToggleOverlayEdit = useCallback(async () => {
    if (isSavingAnnotations) return;
    const isLocking = isEditingOverlay;
    if (setIsEditingOverlay) setIsEditingOverlay((previous) => !previous);
    if (!isLocking || !automaticRoadAnnotations.length) return;
    const merged = mergeGeneratedRoadAnnotations(annotations, automaticRoadAnnotations);
    setAnnotations(merged);
    await persistAnnotations(merged);
  }, [isEditingOverlay, setIsEditingOverlay, annotations, automaticRoadAnnotations, persistAnnotations, isSavingAnnotations]);

  return {
    showAnnotationPanel,
    setShowAnnotationPanel,
    isEditingAnnotations,
    setIsEditingAnnotations,
    activeAnnotationId,
    setActiveAnnotationId,
    selectedAnnotationIds,
    setSelectedAnnotationIds,
    annotations,
    setAnnotations,
    isSavingAnnotations,
    setIsSavingAnnotations,
    allPropertiesAnnotations,
    handleAddAnnotation,
    handleGenerateBlockLabels,
    handleToggleSelectAnnotation,
    handleSelectAllAnnotations,
    handleDeselectAllAnnotations,
    handleUpdateSelectedAnnotations,
    handleDeleteSelectedAnnotations,
    handleUpdateAnnotation,
    handleUpdateAllAnnotations,
    handleDeleteAnnotation,
    handleDeleteAllAnnotations,
    createRoadLabelIcon,
    persistAnnotations,
    handleSaveAnnotations,
    handleToggleOverlayEdit,
  };
}

export default useMapAnnotationsState;
