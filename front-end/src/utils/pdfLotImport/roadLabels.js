const ROAD_PREFIX = /\b(?:ROAD|RD)\s+LOT\s*(?:NO\.?\s*)?[#.:-]?\s*(\d+[A-Z]?(?:[-/]\d+[A-Z]?)?)/i;
const BARE_ROAD = /^(\d+[A-Z]?)(?:\s+[>([]*\s*|[>([]+\s*)(\d+(?:\.\d+)?)\s*(?:METERS?|M\.?)\s*(?:WIDE|W\.?)/i;
const WIDTH = /(\d+(?:\.\d+)?)\s*(?:METERS?|M\.?)\s*(?:WIDE|W\.?)/i;

const angleDistance = (a = 0, b = 0) => {
  const difference = Math.abs((((a - b) % 180) + 180) % 180);
  return Math.min(difference, 180 - difference);
};

const formatRoad = (lot, width) => `ROAD LOT ${lot}${width ? ` (${width} METERS WIDE)` : ""}`;

/** Extract editable road annotations from the already decoded PDF text labels. */
export function extractRoadLabels(labels = [], pageWidth, pageHeight) {
  if (!(pageWidth > 0) || !(pageHeight > 0)) return [];
  const primary = [];
  const widthOnly = [];

  labels.forEach((label, index) => {
    const text = String(label.text || "").replace(/\s+/g, " ").trim();
    const prefix = text.match(ROAD_PREFIX);
    const width = text.match(WIDTH)?.[1] || "";
    const bare = !prefix && text.match(BARE_ROAD);
    if (prefix || bare) {
      primary.push({ label, index, lot: prefix?.[1] || bare[1], width: width || bare?.[2] || "" });
    } else if (width && /^\s*[>([]?\s*\d/i.test(text)) {
      widthOnly.push({ label, width, used: false });
    }
  });

  for (const road of primary) {
    if (road.width) continue;
    let nearest = null, best = Infinity;
    for (const candidate of widthOnly) {
      if (candidate.used || angleDistance(road.label.rotation, candidate.label.rotation) > 12) continue;
      const distance = Math.hypot(road.label.point[0] - candidate.label.point[0], road.label.point[1] - candidate.label.point[1]);
      if (distance < best) { best = distance; nearest = candidate; }
    }
    if (nearest && best <= 35) {
      road.width = nearest.width;
      nearest.used = true;
    }
  }

  return primary.map((road, outputIndex) => ({
    id: `pdf-road-${outputIndex + 1}`,
    text: formatRoad(road.lot, road.width),
    point: [road.label.point[0] / pageWidth, road.label.point[1] / pageHeight],
    rotation: Number.isFinite(road.label.rotation) ? road.label.rotation : 0,
    pageAspect: pageWidth / pageHeight,
    textHeight: (road.label.height || 0) / pageHeight,
    fontSize: 12,
    color: "#e2e8f0",
    autoGenerated: "pdf-road",
  }));
}

export function mergeGeneratedRoadAnnotations(existing = [], generated = []) {
  return [...existing.filter((item) => item.autoGenerated !== "pdf-road"), ...generated.map((item) => {
    const previous = existing.find((old) => old.autoGenerated === "pdf-road" && old.id === item.id && old.sourceName === item.sourceName);
    return previous ? { ...item, ...previous.pdfOverrides, pdfOverrides: previous.pdfOverrides, deleted: previous.deleted } : item;
  })];
}
