import { extractRoadLabels, mergeGeneratedRoadAnnotations } from "./roadLabels";

const label = (text, x, y, rotation = 0) => ({ text, point: [x, y], rotation });

test("normalizes full, abbreviated, split and numeric road labels", () => {
  const roads = extractRoadLabels([
    label("ROAD LOT 9 >10.00 METERS WIDE", 50, 20, 25),
    label("RD LOT 7", 40, 40, -30),
    label("10.00 M. W.", 43, 44, -30),
    label("3 (6.00 M. W.)", 70, 50, 12),
    label("ROADS & ALLEYS", 10, 10),
    label("ROAD LOTS", 10, 15),
  ], 100, 80);

  expect(roads.map((road) => road.text)).toEqual([
    "ROAD LOT 9 (10.00 METERS WIDE)",
    "ROAD LOT 7 (10.00 METERS WIDE)",
    "ROAD LOT 3 (6.00 METERS WIDE)",
  ]);
  expect(roads[0]).toMatchObject({ point: [0.5, 0.25], rotation: 25, color: "#e2e8f0", autoGenerated: "pdf-road" });
});

test("does not attach a distant width note or collapse repeated road labels", () => {
  const roads = extractRoadLabels([
    label("ROAD LOT 1", 10, 10), label("6.50 M. WIDE", 90, 70),
    label("ROAD LOT 9 (10.00 M.WIDE)", 30, 30), label("ROAD LOT 9 (10.00 M.WIDE)", 60, 60),
  ], 100, 80);
  expect(roads.map((road) => road.text)).toEqual([
    "ROAD LOT 1", "ROAD LOT 9 (10.00 METERS WIDE)", "ROAD LOT 9 (10.00 METERS WIDE)",
  ]);
});

test("replaces old generated labels while preserving manual annotations", () => {
  const manual = { id: "manual", text: "Provincial Road" };
  const old = { id: "old", autoGenerated: "pdf-road" };
  const fresh = { id: "fresh", autoGenerated: "pdf-road" };
  expect(mergeGeneratedRoadAnnotations([manual, old], [fresh])).toEqual([manual, fresh]);
});

test("realigning preserves edited fields and deleted labels from the same PDF", () => {
  const generated = [{ id: "pdf-road-1", autoGenerated: "pdf-road", sourceName: "plan.pdf", text: "ROAD LOT 1", lat: 10 },
    { id: "pdf-road-2", autoGenerated: "pdf-road", sourceName: "plan.pdf" }];
  const existing = [{ ...generated[0], lat: 9, pdfOverrides: { text: "Corrected road", color: "#ffffff" } },
    { ...generated[1], deleted: true }];
  const merged = mergeGeneratedRoadAnnotations(existing, generated);
  expect(merged[0]).toMatchObject({ text: "Corrected road", color: "#ffffff", lat: 10 });
  expect(merged[1].deleted).toBe(true);
  expect(mergeGeneratedRoadAnnotations(existing, [{ ...generated[0], sourceName: "other.pdf" }])[0].text).toBe("ROAD LOT 1");
});
